export const getVersesByTopic = (topicId: string): Verse[] => {
  return VERSES.filter(verse => verse.tags.includes(topicId));
};

export const getVerseById = (id: string): Verse | undefined => {
  return VERSES.find(verse => verse.id === id);
};

export const getRandomVerseForTopic = (topicId: string): Verse | null => {
  const topicVerses = getVersesByTopic(topicId);
  if (topicVerses.length === 0) return null;
  return topicVerses[Math.floor(Math.random() * topicVerses.length)];
};

export const getRandomVerseForTopics = (topicIds: string[]): Verse | null => {
  const allVerses = VERSES.filter(verse => 
    verse.tags.some(tag => topicIds.includes(tag))
  );
  if (allVerses.length === 0) return null;
  return allVerses[Math.floor(Math.random() * allVerses.length)];
};
